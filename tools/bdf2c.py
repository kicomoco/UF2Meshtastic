#!/usr/bin/env python3
"""Convert a fixed-width BDF font (<= 8px wide) into a C glyph table.

Covers code points 0x20-0x7E and 0xA0-0xFF (Latin-1) so that UTF-8 node names
with common accented characters render correctly.

Usage: bdf2c.py <font.bdf> <c_symbol_name> > out.c
"""
import sys


def parse_bdf(path):
    glyphs = {}
    width = height = None
    base_y = 0
    with open(path, encoding="latin-1") as f:
        lines = iter(f.read().splitlines())
    for line in lines:
        if line.startswith("FONTBOUNDINGBOX"):
            _, w, h, _x, y = line.split()
            width, height, base_y = int(w), int(h), int(y)
        elif line.startswith("STARTCHAR"):
            enc = None
            bbx = None
            rows = []
            for line in lines:
                if line.startswith("ENCODING"):
                    enc = int(line.split()[1])
                elif line.startswith("BBX"):
                    bbx = [int(v) for v in line.split()[1:]]
                elif line == "BITMAP":
                    for line in lines:
                        if line == "ENDCHAR":
                            break
                        rows.append(int(line, 16))
                    break
            if enc is None or bbx is None:
                continue
            bw, bh, bx, by = bbx
            nbytes = (bw + 7) // 8
            cell = [0] * height
            # Row index within the cell for the top of the glyph bbox
            top = height - (by - base_y) - bh
            for i, r in enumerate(rows):
                y = top + i
                if 0 <= y < height:
                    v = r >> (nbytes * 8 - 8) if nbytes > 1 else r
                    cell[y] = (v >> bx) & 0xFF
            glyphs[enc] = cell
    return width, height, glyphs


def main():
    path, name = sys.argv[1], sys.argv[2]
    w, h, glyphs = parse_bdf(path)
    codes = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100))
    print(f"// Generated by tools/bdf2c.py from {path.split('/')[-1]}")
    print("// Spleen font (c) Frederic Cambus, BSD 2-Clause license.")
    print('#include "font.h"\n')
    print(f"static const uint8_t {name}_data[{len(codes)}][{h}] = {{")
    for c in codes:
        cell = glyphs.get(c, glyphs.get(ord("?")))
        print("    {" + ",".join(f"0x{v:02x}" for v in cell) + f"}}, // 0x{c:02x}")
    print("};\n")
    print(f"const font_t {name} = {{ {w}, {h}, &{name}_data[0][0] }};")


if __name__ == "__main__":
    main()
